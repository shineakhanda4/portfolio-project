import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { load as loadYaml } from "js-yaml";

const root = process.cwd();
const contentDir = path.join(root, "src", "content", "blog");
const outputFile = path.join(root, "src", "generated", "blogIndex.ts");

const categorySlugs = {
  "Web Development": "web-development",
  "React & Next.js": "react-nextjs",
  "TypeScript & JavaScript": "typescript-javascript",
  "Backend Development": "backend-development",
  "Digital Marketing": "digital-marketing",
  "Search Engine Optimization": "seo",
  "Business Growth": "business-growth",
  "Linux & System Administration": "linux-system-administration",
  "Bare-Metal Infrastructure": "bare-metal-infrastructure",
};

function requireString(data, key, filename) {
  const value = data?.[key];
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${filename}: frontmatter "${key}" must be a non-empty string.`);
  }
  return value;
}

function countWords(body) {
  return body
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/[#*_>`[\]()!-]/g, " ")
    .split(/\s+/)
    .filter(Boolean).length;
}

function readingMinutes(wordCount) {
  return Math.max(1, Math.ceil(wordCount / 220));
}

const files = (await readdir(contentDir)).filter((file) => file.endsWith(".md"));
const posts = [];

for (const filename of files) {
  const source = await readFile(path.join(contentDir, filename), "utf8");
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(source);
  if (!match) throw new Error(`${filename}: missing YAML frontmatter.`);

  const data = loadYaml(match[1]);
  const body = source.slice(match[0].length).trim();
  const category = requireString(data, "category", filename);
  const categorySlug = categorySlugs[category];
  if (!categorySlug) {
    throw new Error(`${filename}: unknown category "${category}".`);
  }

  const tags = Array.isArray(data.tags)
    ? data.tags.filter((tag) => typeof tag === "string")
    : [];
  const wordCount = countWords(body);

  posts.push({
    slug: filename.replace(/\.md$/, ""),
    title: requireString(data, "title", filename),
    description: requireString(data, "description", filename),
    excerpt: requireString(data, "excerpt", filename),
    date: requireString(data, "date", filename),
    updated: requireString(data, "updated", filename),
    categorySlug,
    tags,
    featured: data.featured === true,
    cover: requireString(data, "cover", filename),
    coverAlt: requireString(data, "coverAlt", filename),
    readingMinutes: readingMinutes(wordCount),
    wordCount,
    order: typeof data.order === "number" ? data.order : 999,
  });
}

posts.sort((a, b) => (a.order !== b.order ? a.order - b.order : b.date.localeCompare(a.date)));

const source = `// Generated by scripts/generate-blog-index.mjs. Do not edit by hand.
// Run "npm run blog:index" after changing an article's frontmatter.
import type { BlogPostSummary } from "@/types/content";

export const BLOG_INDEX: BlogPostSummary[] = ${JSON.stringify(posts, null, 2)};
`;

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, source, "utf8");
console.log(`Generated blog metadata for ${posts.length} articles.`);
